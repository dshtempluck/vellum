"""Emit the DjVu ZP-coder state table as a C++ include.

The 256-state adaptive probability machine is part of the DjVu bitstream
format definition; the numbers are interoperability constants without which
no conforming DjVu file can be decoded.

Usage: python gen_zptable.py <path to ZPCodec.cpp> <output .inc>
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
i = src.index("default_ztable[256]")
blk = src[i:src.index("};", i)]
a = blk.index("#ifdef ZPCODER")
b = blk.index("#endif", a)
body = blk[a:b]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)   # drop per-row comments
body = re.sub(r"//[^\n]*", "", body)

rows = re.findall(r"\{([^{}]*)\}", body)
parsed = []
for r in rows:
    f = [x.strip() for x in r.split(",") if x.strip()]
    if len(f) != 4:
        continue
    parsed.append([int(x, 0) for x in f])

# The format defines states 0..250; the array is declared [256] and the
# five trailing slots are zero padding. Reproduce that exactly.
if len(parsed) != 251:
    sys.exit(f"expected 251 defined states, parsed {len(parsed)}")
parsed += [[0, 0, 0, 0]] * (256 - len(parsed))

out = [
    "// DjVu ZP-coder adaptive probability state machine (256 states).",
    "// Entries are {pmax, mmax, up, dn} exactly as defined by the DjVu",
    "// bitstream format. These are interoperability constants: they are",
    "// required to decode any conforming DjVu file.",
    "// Generated by tools/gen_zptable.py -- do not edit by hand.",
    "",
    "const ZpState kZpTable[256] = {",
]
for n, (p, m, up, dn) in enumerate(parsed):
    out.append(f"    {{ 0x{p:04x}, 0x{m:04x}, {up:>3}, {dn:>3} }},  // {n}")
out.append("};")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote 256 states -> {sys.argv[2]}")
