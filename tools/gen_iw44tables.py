"""Emit IW44 format constant tables as a C++ include.

iw_quant holds the per-subband quantization steps and zigzagloc maps the
1024 coefficients of a 32x32 block to their position in the band/bucket
layout. Both are definitions of the DjVu IW44 bitstream, required for
interoperability.

Usage: python gen_iw44tables.py <IW44Image.cpp> <output .inc>
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8", errors="replace").read()


def table(marker, count):
    i = src.index(marker)
    blk = src[i:src.index("};", i)]
    blk = blk[blk.index("{") + 1:]
    blk = re.sub(r"/\*.*?\*/", "", blk, flags=re.S)
    blk = re.sub(r"//[^\n]*", "", blk)
    vals = [int(t, 0) for t in re.findall(r"0x[0-9a-fA-F]+|\d+", blk)]
    if len(vals) != count:
        sys.exit(f"{marker}: expected {count} values, got {len(vals)}")
    return vals


quant = table("iw_quant[16]", 16)
zigzag = table("zigzagloc[1024]", 1024)

out = [
    "// IW44 wavelet codec constant tables (DjVu bitstream definitions).",
    "// Generated by tools/gen_iw44tables.py -- do not edit by hand.",
    "",
    "// Quantization step for each of the 16 wavelet sub-bands.",
    "static const int kIwQuant[16] = {",
]
for r in range(0, 16, 4):
    out.append("    " + ", ".join(f"0x{v:06x}" for v in quant[r:r + 4]) + ",")
out.append("};")
out += [
    "",
    "// Maps each of the 1024 coefficients of a 32x32 block to its index in",
    "// the band/bucket ordering used by the bitstream.",
    "static const short kZigzagLoc[1024] = {",
]
for r in range(0, 1024, 16):
    out.append("    " + ", ".join(f"{v:4d}" for v in zigzag[r:r + 16]) + ",")
out.append("};")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote iw_quant[16] + zigzagloc[1024] -> {sys.argv[2]}")
